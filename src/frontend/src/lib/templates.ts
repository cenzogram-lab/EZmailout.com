let fontsReady: Promise<void> | null = null;

/**
 * Loads every typeface a template sets. Layouts are measured with canvas
 * text metrics, which silently fall back to another face until the real
 * one has loaded, so build a template only after this resolves.
 */
export function loadTemplateFonts(): Promise<void> {
  if (typeof document === "undefined" || !("fonts" in document))
    return Promise.resolve();
  fontsReady ??= Promise.all(
    TEMPLATE_FONT_FACES.map((f) => document.fonts.load(f).catch(() => [])),
  )
    .then(() => undefined)
    .catch(() => undefined);
  return fontsReady;
}

/** True once `loadTemplateFonts` has finished (synchronous check). */
export function templateFontsLoaded(): boolean {
  if (typeof document === "undefined" || !("fonts" in document)) return true;
  return TEMPLATE_FONT_FACES.every((f) => document.fonts.check(f));
}
