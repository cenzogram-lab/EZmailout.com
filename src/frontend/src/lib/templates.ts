/** Catalog family a template is shown under ("Postcards", "Letters", …). */
export function templateCategory(t: DesignTemplate): string {
  return categoryForVariant(t.layoutVariant)?.name ?? "Postcards";
}

/** Lowest price per piece of the template's format ("from"), in cents. */
export function templatePriceCents(t: DesignTemplate): number {
  return getPricingRow(t.layoutVariant)
    ? startingPriceCents(t.layoutVariant)
    : 0;
}

export function templatePriceBand(t: DesignTemplate): TemplatePriceBand {
  const c = templatePriceCents(t);
  return (
    TEMPLATE_PRICE_BANDS.find((b) => c >= b.min && c <= b.max) ??
    TEMPLATE_PRICE_BANDS[0]
  ).id;
}

/** Catalog families that have at least one template, in catalog order. */
export function templateCategories(): string[] {
  return [...new Set(TEMPLATES.map(templateCategory))];
}

/** Every template; the ones written for this format first, then its family, then the rest. */
export function templatesForLayout(
  layoutVariant: string,
  productType: ProductType | null,
): DesignTemplate[] {
  const rank = (t: DesignTemplate) =>
    t.layoutVariant === layoutVariant
      ? 0
      : productType && t.productType === productType
        ? 1
        : 2;
  return [...TEMPLATES].sort((a, b) => rank(a) - rank(b));
}

