type Input = Omit<
  DesignTemplate,
  "productType" | "features" | "orientation"
> & {
  orientation?: DesignTemplate["orientation"];
};

function featuresOf(t: Input): TemplateFeature[] {
  const f: TemplateFeature[] = [];
  if (t.hasQrCode) f.push("QR code");
  if (t.copy.offer) f.push("Coupon or offer");
  if (t.copy.bullets.length > 0) f.push("Checklist");
  if (t.copy.details?.length) f.push("Event details");
  if (t.archetype !== "classic" && t.archetype !== "poster")
    f.push("Illustration");
  if (t.archetype === "letterhead") f.push("Signature");
  return f;
}

function define(t: Input): DesignTemplate {
  const row = getPricingRow(t.layoutVariant);
  if (!row) throw new Error(`Unknown template format ${t.layoutVariant}`);
  return {
    ...t,
    orientation: t.orientation ?? "native",
    productType: row.productType as ProductType,
    features: featuresOf(t),
  };
}

