import type { MailColors } from "./types";

/**
 * Print palettes. Checked by tools/check-contrast: text/bg, muted/bg,
 * text/surface, onAccent/accent and onAccent2/accent2 all ≥ 4.5:1.
 * Order: bg, surface, text, muted, accent, onAccent, accent2, onAccent2, border
 */
function p(
  bg: string,
  surface: string,
  text: string,
  muted: string,
  accent: string,
  onAccent: string,
  accent2: string,
  onAccent2: string,
  border: string,
): MailColors {
  return {
    bg,
    surface,
    text,
    muted,
    accent,
    onAccent,
    accent2,
    onAccent2,
    border,
  };
}

