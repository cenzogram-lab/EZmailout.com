export const SIDES_OF: Record<1 | 2 | 4, Side[]> = {
  1: ["front"],
  2: ["front", "back"],
  4: ["front", "inside-left", "inside-right", "back"],
};

export function getFormat(id: FormatId): FormatDef {
  return FORMATS[id];
}

/** Pixel box for a format, with or without bleed. */
export function pieceSize(fmt: FormatDef, bleed: boolean) {
  const b = bleed ? fmt.bleed : 0;
  return {
    w: inToPx(fmt.width + 2 * b),
    h: inToPx(fmt.height + 2 * b),
    bleedPx: inToPx(b),
    safePx: inToPx(fmt.safe),
  };
}

/** CSS @page rule for printing a format at exact size (with bleed when requested). */
export function pageCss(fmt: FormatDef, bleed: boolean): string {
  const b = bleed ? fmt.bleed : 0;
  return `@page{size:${fmt.width + 2 * b}in ${fmt.height + 2 * b}in;margin:0}`;
}
