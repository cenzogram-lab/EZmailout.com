/**
 * Sample campaign content used by the gallery previews. One set per
 * industry/campaign. Replace with real MailContent in production.
 */

const indicia = (city: string, permit = "PERMIT NO. 1042") => ({
  line1: "PRSRT STD",
  line2: "U.S. POSTAGE PAID",
  line3: `${city.toUpperCase()}\n${permit}`.replace("\n", " · "),
});

/**
 * Contact details are placeholders, like the rest of the template library:
 * a real-looking street or domain could belong to someone, and a customer
 * who forgets to change it would print it. Phone numbers are 555-01xx.
 */
function placeholderContacts(c: MailContent): MailContent {
  const b = c.business;
  return {
    ...c,
    business: {
      ...b,
      website: b.website ? "yourwebsite.com" : b.website,
      email: b.email ? "hello@yourwebsite.com" : b.email,
      address: b.address ? "123 Anywhere St." : b.address,
      city: b.city ? "Any City, ST 00000" : b.city,
    },
  };
}

function set(raw: MailContent): MailContent {
  const c = placeholderContacts(raw);
  return {
    ...c,
    qr: c.qr ?? {
      url: c.business.website ?? "example.com",
      caption: "Scan to book",
    },
    mailing: c.mailing ?? {
      indicia: indicia(c.business.city?.split(",")[0] ?? "Anytown"),
      returnAddress: [
        c.business.name,
        c.business.address ?? "",
        c.business.city ?? "",
      ].filter(Boolean),
    },
  };
}

